/* eslint-disable no-continue */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const projectRoot = process.cwd();
const sourceRoots = ['src', 'packages', 'apifox-mock/data'];
const sourceExtensions = new Set(['.ts', '.tsx', '.vue', '.json']);
const iconPattern = /\b([a-z][a-z0-9-]*):([a-z0-9][a-z0-9-]*)\b/g;
const outputPath = path.join(projectRoot, 'src/assets/iconify-offline.ts');

function collectSourceFiles(directory, files = []) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      collectSourceFiles(entryPath, files);
    } else if (sourceExtensions.has(path.extname(entry.name))) {
      files.push(entryPath);
    }
  }

  return files;
}

const candidates = new Map();

for (const sourceRoot of sourceRoots) {
  const rootPath = path.join(projectRoot, sourceRoot);

  for (const filePath of collectSourceFiles(rootPath)) {
    const source = fs.readFileSync(filePath, 'utf8');

    for (const match of source.matchAll(iconPattern)) {
      const [, prefix, name] = match;

      if (!candidates.has(prefix)) candidates.set(prefix, new Set());
      candidates.get(prefix).add(name);
    }
  }
}

const collections = [];
let iconCount = 0;

for (const prefix of [...candidates.keys()].sort()) {
  const collectionPath = path.join(projectRoot, 'node_modules/@iconify/json/json', `${prefix}.json`);

  if (!fs.existsSync(collectionPath)) continue;

  const sourceCollection = JSON.parse(fs.readFileSync(collectionPath, 'utf8'));
  const icons = {};
  const aliases = {};

  function includeIcon(name) {
    if (icons[name] || aliases[name]) return;

    if (sourceCollection.icons?.[name]) {
      icons[name] = sourceCollection.icons[name];
      return;
    }

    if (sourceCollection.aliases?.[name]) {
      const alias = sourceCollection.aliases[name];
      aliases[name] = alias;
      includeIcon(alias.parent);
    }
  }

  for (const name of [...candidates.get(prefix)].sort()) includeIcon(name);

  if (Object.keys(icons).length === 0 && Object.keys(aliases).length === 0) continue;

  const collection = {
    prefix: sourceCollection.prefix,
    icons
  };

  if (Object.keys(aliases).length > 0) collection.aliases = aliases;
  if (sourceCollection.width) collection.width = sourceCollection.width;
  if (sourceCollection.height) collection.height = sourceCollection.height;

  collections.push(collection);
  iconCount += Object.keys(icons).length + Object.keys(aliases).length;
}

if (iconCount === 0) {
  throw new Error('No Iconify icons were found in the configured source roots.');
}

const output = `/* eslint-disable */
// Generated by scripts/generate-offline-icons.mjs. Run \`pnpm gen-icons\` after adding runtime Iconify names.
import type { IconifyJSON } from '@iconify/vue/offline';

const offlineIconCollections: IconifyJSON[] = ${JSON.stringify(collections, null, 2)};

export default offlineIconCollections;
`;

fs.writeFileSync(outputPath, output.replaceAll('\r\n', '\n'), 'utf8');
console.log(`Generated ${iconCount} offline Iconify icons from ${collections.length} collections.`);
